/**
 * Cookie import/export service.
 *
 * Requirements (SPEC.md §8 & §10):
 *  - JSON and Netscape formats, per profile.
 *  - Never eval or execute content from cookies or imported files.
 *  - All browser operations go through BrowserEngine or active RunningBrowser.
 */

import type { BrowserCookie, CookieFormat } from '../../shared/types';
import { getProfile } from './profile-service';
import { getRunningBrowser } from './launcher-service';
import { ChromiumPlaywrightEngine } from '../engine/chromium-playwright';

const engine = new ChromiumPlaywrightEngine();

/**
 * Parses JSON format cookies.
 * Supports standard Playwright format, EditThisCookie, and Puppeteer formats.
 */
export function parseJsonCookies(raw: string): BrowserCookie[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(`Invalid JSON cookie format: ${err instanceof Error ? err.message : String(err)}`);
  }

  const items = Array.isArray(parsed) ? parsed : [parsed];
  const cookies: BrowserCookie[] = [];

  for (const item of items) {
    if (typeof item !== 'object' || item === null) continue;
    const obj = item as Record<string, unknown>;

    const name = typeof obj.name === 'string' ? obj.name : '';
    const value = typeof obj.value === 'string' ? obj.value : '';
    const domain = typeof obj.domain === 'string' ? obj.domain : '';
    const path = typeof obj.path === 'string' ? obj.path : '/';

    if (!name || !domain) continue;

    let expires: number | undefined;
    if (typeof obj.expires === 'number' && !isNaN(obj.expires) && obj.expires > 0) {
      expires = obj.expires;
    } else if (typeof obj.expirationDate === 'number' && !isNaN(obj.expirationDate) && obj.expirationDate > 0) {
      expires = obj.expirationDate;
    }

    const httpOnly = Boolean(obj.httpOnly);
    const secure = Boolean(obj.secure);

    let sameSite: 'Strict' | 'Lax' | 'None' | undefined;
    if (typeof obj.sameSite === 'string') {
      const lower = obj.sameSite.toLowerCase();
      if (lower === 'strict') sameSite = 'Strict';
      else if (lower === 'lax') sameSite = 'Lax';
      else if (lower === 'none' || lower === 'no_restriction') sameSite = 'None';
    }

    cookies.push({
      name,
      value,
      domain,
      path,
      expires,
      httpOnly,
      secure,
      sameSite,
    });
  }

  return cookies;
}

/**
 * Serializes cookies to standard JSON format.
 */
export function serializeJsonCookies(cookies: BrowserCookie[]): string {
  return JSON.stringify(cookies, null, 2);
}

/**
 * Parses standard Netscape HTTP cookie format file.
 * Handles '#HttpOnly_' prefix for HttpOnly cookies as standard in curl/browser cookie files.
 */
export function parseNetscapeCookies(raw: string): BrowserCookie[] {
  const lines = raw.split(/\r?\n/);
  const cookies: BrowserCookie[] = [];

  for (let line of lines) {
    line = line.trim();
    if (!line) continue;

    let httpOnly = false;
    if (line.startsWith('#HttpOnly_')) {
      httpOnly = true;
      line = line.substring('#HttpOnly_'.length);
    } else if (line.startsWith('#')) {
      // General comment, skip
      continue;
    }

    // Tab-delimited (fallback to multi-space if user pasted with spaces)
    let parts = line.split('\t');
    if (parts.length < 7) {
      parts = line.split(/\s+/);
    }

    if (parts.length < 7) continue;

    const domain = parts[0];
    // parts[1] is includeSubdomains (flag)
    const path = parts[2] || '/';
    const isSecure = parts[3].toUpperCase() === 'TRUE';
    const expirySec = parseInt(parts[4], 10);
    const name = parts[5];
    const value = parts.slice(6).join(' '); // in case value had spaces

    if (!name || !domain) continue;

    cookies.push({
      name,
      value,
      domain,
      path,
      expires: !isNaN(expirySec) && expirySec > 0 ? expirySec : undefined,
      httpOnly,
      secure: isSecure,
    });
  }

  return cookies;
}

/**
 * Serializes cookies to standard Netscape HTTP cookie format.
 */
export function serializeNetscapeCookies(cookies: BrowserCookie[]): string {
  const header = [
    '# Netscape HTTP Cookie File',
    '# http://curl.haxx.se/rfc/cookie_spec.html',
    '# This file was generated by ProfileBrowser. Do not edit.',
    '',
  ];

  const rows = cookies.map((c) => {
    const prefix = c.httpOnly ? '#HttpOnly_' : '';
    const domain = c.domain;
    const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const path = c.path || '/';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expires = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0;
    return `${prefix}${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expires}\t${c.name}\t${c.value}`;
  });

  return [...header, ...rows].join('\n');
}

/**
 * Exports cookies for a given profile.
 */
export async function exportCookies(profileId: string, format: CookieFormat = 'json'): Promise<string> {
  const profile = getProfile(profileId);
  if (!profile) throw new Error(`Profile not found: ${profileId}`);

  let cookies: BrowserCookie[] = [];
  const running = getRunningBrowser(profileId);

  if (running && running.getCookies) {
    cookies = await running.getCookies();
  } else {
    cookies = await engine.getCookies(profile.userDataDir);
  }

  if (format === 'netscape') {
    return serializeNetscapeCookies(cookies);
  }
  return serializeJsonCookies(cookies);
}

/**
 * Imports cookies into a given profile.
 */
export async function importCookies(
  profileId: string,
  content: string,
  format: CookieFormat = 'json'
): Promise<{ count: number }> {
  const profile = getProfile(profileId);
  if (!profile) throw new Error(`Profile not found: ${profileId}`);

  const cookies =
    format === 'netscape' ? parseNetscapeCookies(content) : parseJsonCookies(content);

  if (cookies.length === 0) {
    throw new Error('No valid cookies found in provided content');
  }

  const running = getRunningBrowser(profileId);
  if (running && running.addCookies) {
    await running.addCookies(cookies);
  } else {
    await engine.addCookies(profile.userDataDir, cookies);
  }

  return { count: cookies.length };
}
